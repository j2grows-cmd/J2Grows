UPDATE public.species AS s
SET rarity = e.rarity,
    difficulty = COALESCE(s.difficulty, 'Moderate'),
    light = COALESCE(NULLIF(BTRIM(s.light), ''), 'Not recorded'),
    humidity = COALESCE(NULLIF(BTRIM(s.humidity), ''), 'Not recorded'),
    water = COALESCE(NULLIF(BTRIM(s.water), ''), 'Not recorded'),
    traits = CASE WHEN COALESCE(cardinality(s.traits), 0) = 0 THEN ARRAY['Not yet researched']::text[] ELSE s.traits END
FROM economy AS e
WHERE LOWER(REGEXP_REPLACE(BTRIM(s.name), '[^a-zA-Z0-9]+', ' ', 'g')) = LOWER(REGEXP_REPLACE(BTRIM(e.name), '[^a-zA-Z0-9]+', ' ', 'g'));
